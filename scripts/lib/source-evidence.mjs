import crypto from 'node:crypto';
import { z } from 'astro/zod';

export const EXTRACTOR_VERSION = 'govinfo-usc-html-v1';
export const MAX_SOURCE_BYTES = 512 * 1024;
export const digest = (bytes) =>
  crypto.createHash('sha256').update(bytes).digest('hex');
const sha = z.string().regex(/^[a-f0-9]{64}$/);
const id = z.string().regex(/^[a-z0-9][a-z0-9-]*$/);
const languageCode = z.string().regex(/^[a-z]{2}(?:-[a-z0-9]+)?$/i);
const date = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/)
  .refine((value) => {
    const parsed = new Date(`${value}T00:00:00Z`);
    return (
      !Number.isNaN(parsed.getTime()) &&
      parsed.toISOString().slice(0, 10) === value
    );
  }, 'A valid calendar date is required.');
const review = z
  .object({
    status: z.enum(['draft', 'verified']),
    reviewer: z.string().trim().min(1).nullable(),
    method: z.enum(['not_reviewed', 'human']),
    reviewed_at: date.nullable(),
  })
  .strict()
  .refine(
    (v) =>
      v.status !== 'verified' ||
      (v.method === 'human' && v.reviewer && v.reviewed_at),
    'Verified evidence requires a named reviewer and date.'
  );

export class EvidenceError extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

const GOVINFO_ENTITIES = Object.freeze({
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  sect: '§',
  mdash: '—',
  ndash: '–',
  lsquo: '‘',
  rsquo: '’',
  ldquo: '“',
  rdquo: '”',
  thinsp: ' ',
});

const OFFICIAL_HTML_ENTITIES = Object.freeze({
  ...GOVINFO_ENTITIES,
  ccedil: 'ç',
  times: '×',
});

const GOVINFO_URL_RE =
  /^https:\/\/www\.govinfo\.gov\/content\/pkg\/USCODE-\d{4}-title26\/html\/USCODE-\d{4}-title26-subtitleA-chap1-subchapA-partIV-subpartD-sec45Q\.htm$/;

const CHALLENGE_OR_ERROR_HTML_RE =
  /(?:<title[^>]*>[^<]*(?:404|403|500|502|503|page not found|not found|access denied|forbidden|just a moment|attention required|request blocked|sign in|error)[^<]*<\/title>|generated by cloudfront|the request could not be satisfied|enable javascript and cookies to continue|cf-browser-verification|aws-waf|<input[^>]*type=["']password)/i;

const CHALLENGE_OR_ERROR_TEXT_RE =
  /^(?:page not found|404 not found|access denied|forbidden|just a moment\.\.\.|attention required!|the request could not be satisfied|enable javascript and cookies to continue)$/i;

function decodeUtf8Strict(raw) {
  if (raw.length > MAX_SOURCE_BYTES)
    throw new EvidenceError(
      'SOURCE_TOO_LARGE',
      'The source snapshot exceeds 512 KiB.'
    );
  return new TextDecoder('utf-8', { fatal: true }).decode(raw);
}

function decodeHtmlEntities(text, entityMap) {
  return text.replace(/&(#x[\da-f]+|#\d+|[a-z][a-z\d]+);/gi, (_, key) => {
    if (key.startsWith('#')) {
      const cp =
        key[1].toLowerCase() === 'x'
          ? parseInt(key.slice(2), 16)
          : Number(key.slice(1));
      if (cp > 0x10ffff || cp < 1 || (cp >= 0xd800 && cp <= 0xdfff))
        throw new EvidenceError('INVALID_ENTITY', 'Invalid Unicode entity.');
      return String.fromCodePoint(cp);
    }
    if (!(key in entityMap))
      throw new EvidenceError(
        'UNSUPPORTED_ENTITY',
        `Unsupported entity: ${key}`
      );
    return entityMap[key];
  });
}

function extractBody(html) {
  const body = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1];
  if (!body) throw new EvidenceError('UNEXPECTED_SOURCE', 'No document body.');
  return body;
}

function normalizeTextLines(text, { spaceRe, stripRe = null }) {
  const cleaned = (stripRe ? text.replace(stripRe, '') : text)
    .normalize('NFC')
    .replace(/\r/g, '');
  const lines = cleaned
    .split('\n')
    .map((line) => line.replace(spaceRe, ' ').trim())
    .filter(Boolean);
  if (!lines.length)
    throw new EvidenceError('UNEXPECTED_SOURCE', 'Empty document body.');
  return lines.join('\n') + '\n';
}

export const EXTRACTORS = Object.freeze({
  'govinfo-usc-html-v1': {
    normalize(raw) {
      const html = decodeUtf8Strict(raw);
      if (
        !html.includes('<!-- documentid:26_45Q ') ||
        !html.includes('class="section-head"')
      )
        throw new EvidenceError(
          'UNEXPECTED_SOURCE',
          'Not the supported official USC 45Q document; an HTTP 200 is insufficient.'
        );
      const body = extractBody(html)
        .replace(/<!--[^]*?-->/g, '')
        .replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, '')
        .replace(/<\/?(?:p|h[1-6]|div|br|li|tr)\b[^>]*>/gi, '\n')
        .replace(/<[^>]*>/g, '');
      return normalizeTextLines(decodeHtmlEntities(body, GOVINFO_ENTITIES), {
        spaceRe: /[\t \u00a0]+/g,
      });
    },
    validateMetadata(packet, raw, text) {
      const currentThrough = /currentthrough:(\d{4})(\d{2})(\d{2})/.exec(
        new TextDecoder().decode(raw)
      );
      if (
        !currentThrough ||
        currentThrough.slice(1).join('-') !== packet.source_current_through
      )
        throw new EvidenceError(
          'EDITION_MISMATCH',
          'Coverage date must match the source metadata.'
        );
      if (
        !text.includes(`United States Code, ${packet.edition} Edition`) ||
        !packet.source_url.includes(
          `USCODE-${packet.edition}-title26/html/USCODE-${packet.edition}-title26-`
        )
      )
        throw new EvidenceError(
          'EDITION_MISMATCH',
          'Source URL, edition and text disagree.'
        );
    },
  },
  'official-html-v1': {
    normalize(raw) {
      const html = decodeUtf8Strict(raw);
      if (CHALLENGE_OR_ERROR_HTML_RE.test(html))
        throw new EvidenceError(
          'UNEXPECTED_SOURCE',
          'Rejected HTTP error, login, or WAF challenge shell.'
        );
      const body = extractBody(html)
        .replace(/<!--[^]*?-->/g, '')
        .replace(/<(script|style|noscript)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, '')
        .replace(
          /<\/?(?:p|h[1-6]|div|br|li|tr|section|article|dt|dd)\b[^>]*>/gi,
          '\n'
        )
        .replace(/<[^>]*>/g, '');
      const normalized = normalizeTextLines(
        decodeHtmlEntities(body, OFFICIAL_HTML_ENTITIES),
        {
          spaceRe: /[\t \u00a0\u2002\u2003\u2009]+/g,
          stripRe: /\u200d/g,
        }
      );
      if (CHALLENGE_OR_ERROR_TEXT_RE.test(normalized.trim()))
        throw new EvidenceError(
          'UNEXPECTED_SOURCE',
          'Rejected empty or error-shell body.'
        );
      return normalized;
    },
  },
});

const extractorVersionSchema = z.enum(Object.keys(EXTRACTORS));

export const evidencePacketSchema = z
  .object({
    schema_version: z.literal('1.0.0'),
    storage: z.enum(['git_inline', 'external_archive']).optional(),
    document_id: id,
    policy_id: id,
    title: z.object({ en: z.string().min(1), zh: z.string().min(1) }).strict(),
    source_url: z
      .string()
      .url()
      .refine((v) => {
        try {
          return ['http:', 'https:'].includes(new URL(v).protocol);
        } catch {
          return false;
        }
      }, 'Source URL must use HTTP or HTTPS.'),
    source_language: languageCode.default('en'),
    edition: z.string().min(1).nullable(),
    fetched_at: z.string().datetime(),
    published_at: date.nullable(),
    source_current_through: date.nullable(),
    external_uri: z
      .string()
      .url()
      .refine(
        (v) => v.startsWith('https://'),
        'External archive URI must use HTTPS.'
      )
      .optional(),
    bytes: z.number().int().positive().optional(),
    raw_file: z.literal('source.html').nullable().optional(),
    raw_sha256: sha,
    normalized_sha256: sha,
    extractor_version: extractorVersionSchema,
    review,
    anchors: z
      .array(
        z
          .object({
            id,
            locator: z.string().min(1),
            exact_quote: z.string().min(1),
            version_sha256: sha,
            start_offset: z.number().int().nonnegative().nullable().optional(),
            end_offset: z.number().int().positive().nullable().optional(),
            review,
          })
          .strict()
      )
      .min(1),
  })
  .strict()
  .superRefine((val, ctx) => {
    const storage = val.storage ?? 'git_inline';
    if (storage === 'git_inline' && val.raw_file !== 'source.html') {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['raw_file'],
        message: 'git_inline evidence requires raw_file to be "source.html".',
      });
    }
    if (storage === 'external_archive') {
      if (!val.external_uri) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['external_uri'],
          message: 'external_archive evidence requires an HTTPS external_uri.',
        });
      }
      if (typeof val.bytes !== 'number') {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['bytes'],
          message: 'external_archive evidence requires positive integer bytes.',
        });
      }
    }
    if (val.extractor_version === 'govinfo-usc-html-v1') {
      if (!GOVINFO_URL_RE.test(val.source_url))
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['source_url'],
          message: 'Only the pilot official 45Q source is allowed.',
        });
      if (!val.edition || !/^\d{4}$/.test(val.edition))
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['edition'],
          message: 'govinfo-usc-html-v1 requires a 4-digit edition year.',
        });
      if (!val.source_current_through)
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['source_current_through'],
          message: 'govinfo-usc-html-v1 requires source_current_through.',
        });
    }
  });

// Deliberately narrow profiles, not a general web crawler/parser. Unknown
// entity or unexpected source shape fails closed rather than silently losing text.
export function normalizeOfficialHtml(
  raw,
  extractorVersion = EXTRACTOR_VERSION
) {
  const extractor = EXTRACTORS[extractorVersion];
  if (!extractor)
    throw new EvidenceError(
      'UNSUPPORTED_EXTRACTOR',
      `Unsupported extractor: ${extractorVersion}`
    );
  return extractor.normalize(raw);
}

export function inspectEvidence(
  input,
  raw = null,
  { observedRaw, extractorVersion, normalizedText } = {}
) {
  const packet = evidencePacketSchema.parse(input);
  const storage = packet.storage ?? 'git_inline';
  let text = null;
  if (storage === 'git_inline') {
    if (raw == null)
      throw new EvidenceError(
        'MISSING_RAW_SOURCE',
        'git_inline evidence requires source.html bytes.'
      );
    if (digest(raw) !== packet.raw_sha256)
      throw new EvidenceError(
        'RAW_HASH_MISMATCH',
        'Stored bytes do not match the frozen raw hash.'
      );
    text = normalizeOfficialHtml(raw, packet.extractor_version);
    if (digest(text) !== packet.normalized_sha256)
      throw new EvidenceError(
        'TEXT_HASH_MISMATCH',
        'Normalized text differs from the frozen extraction.'
      );
  } else {
    if (raw != null) {
      if (raw.length !== packet.bytes)
        throw new EvidenceError(
          'BYTES_MISMATCH',
          'Stored bytes do not match the declared external archive byte count.'
        );
      if (digest(raw) !== packet.raw_sha256)
        throw new EvidenceError(
          'RAW_HASH_MISMATCH',
          'Stored bytes do not match the frozen raw hash.'
        );
      text = normalizeOfficialHtml(raw, packet.extractor_version);
      if (digest(text) !== packet.normalized_sha256)
        throw new EvidenceError(
          'TEXT_HASH_MISMATCH',
          'Normalized text differs from the frozen extraction.'
        );
    } else if (normalizedText != null) {
      text =
        typeof normalizedText === 'string'
          ? normalizedText
          : Buffer.from(normalizedText).toString('utf8');
      if (digest(text) !== packet.normalized_sha256)
        throw new EvidenceError(
          'TEXT_HASH_MISMATCH',
          'Normalized text differs from the frozen extraction.'
        );
    }
  }
  const ids = new Set();
  const changed =
    observedRaw !== undefined
      ? digest(observedRaw) !== packet.raw_sha256
      : raw != null
        ? digest(raw) !== packet.raw_sha256
        : false;
  const effectiveExtractor = extractorVersion ?? packet.extractor_version;
  const parserChanged = effectiveExtractor !== packet.extractor_version;
  const anchors = packet.anchors.map((anchor) => {
    if (ids.has(anchor.id))
      throw new EvidenceError('DUPLICATE_ANCHOR', 'Anchor IDs must be unique.');
    ids.add(anchor.id);
    if (anchor.version_sha256 !== packet.raw_sha256)
      throw new EvidenceError(
        'ANCHOR_VERSION_MISMATCH',
        'Anchor references another source version.'
      );
    let start = anchor.start_offset ?? null;
    let end = anchor.end_offset ?? null;
    if (text !== null) {
      start = text.indexOf(anchor.exact_quote);
      if (start < 0 || text.indexOf(anchor.exact_quote, start + 1) >= 0)
        throw new EvidenceError(
          'ANCHOR_NOT_UNIQUE',
          'Each exact quote must resolve once in the frozen text.'
        );
      end = start + anchor.exact_quote.length;
    }
    const state = changed
      ? 'source_changed'
      : parserChanged
        ? 'extractor_changed'
        : packet.review.status !== 'verified' ||
            anchor.review.status !== 'verified'
          ? 'needs_review'
          : 'verified';
    return {
      ...anchor,
      start_offset: start,
      end_offset: end,
      offset_unit: 'utf16_code_units',
      state,
      usable_as_reviewed_reference: state === 'verified',
    };
  });
  if (raw != null && text !== null)
    EXTRACTORS[packet.extractor_version].validateMetadata?.(packet, raw, text);
  return {
    storage,
    external_uri: packet.external_uri ?? null,
    bytes: packet.bytes ?? (raw ? raw.length : null),
    document_id: packet.document_id,
    policy_id: packet.policy_id,
    source_language: packet.source_language,
    raw_sha256: packet.raw_sha256,
    normalized_sha256: packet.normalized_sha256,
    extractor_version: packet.extractor_version,
    source_current_through: packet.source_current_through,
    source_currentness_verified: false,
    observed_source_changed: changed,
    requires_review: anchors.some((a) => !a.usable_as_reviewed_reference),
    anchors,
    normalized_text: text,
  };
}
